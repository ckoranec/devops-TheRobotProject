def test_changed_token():  # Test rejection after changing one character.
    import pytest  # Import the test assertion helper.
    signer = token_serializer(secrets.token_urlsafe(48))  # Create a fresh test signer.
    state = secrets.token_urlsafe(32)  # Create a pending request identifier.
